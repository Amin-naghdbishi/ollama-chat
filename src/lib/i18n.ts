export function getTranslation(lang: Language = "en", key: TranslationKey): string {
  const dict = translations[lang] || translations.en;
  return dict[key] || translations.en[key] || (key as string);
}

export function isRtlText(text: string): boolean {
  if (!text) return false;
  // Remove markdown code blocks and inline code before checking
  const cleanText = text
    .replace(/```[\s\S]*?```/g, "")
    .replace(/`[^`]*`/g, "")
    .trim();
  if (!cleanText) return false;

  const rtlRegex = /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF]/g;
  const matches = cleanText.match(rtlRegex);
  if (!matches) return false;

  const nonSpaceLength = cleanText.replace(/\s+/g, "").length;
  return nonSpaceLength > 0 ? matches.length / nonSpaceLength > 0.12 : false;
}
